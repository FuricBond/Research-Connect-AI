/** A subfield's name; an unlisted one by its field; otherwise words, never the raw identifier. */
export function subfieldLabel(id: string): string {
  const known = SUBFIELDS[id];
  if (known) return known;
  const field = /^\d{4}$/.test(id) ? FIELDS[id.slice(0, 2)] : undefined;
  return field ? `Other ${field}` : "Other subject area";
}
